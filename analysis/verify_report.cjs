const { chromium } = require('C:/Users/marce/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  const requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
  await page.goto(pathToFileURL(path.resolve('tarvo-economic-analysis.html')).href);
  await page.screenshot({ path: 'analysis/report-desktop.png', fullPage: true });
  console.log('PAGE ERRORS', errors);
  assert.equal(errors.length, 0);
  assert.equal(requests.length, 0);
  assert.match(await page.locator('#result-count').innerText(), /1\.943/);
  await page.selectOption('#dataset', 'differences');
  assert.match(await page.locator('#result-count').innerText(), /88 registros/);
  await page.fill('#search', '1074504011');
  assert.match(await page.locator('#result-count').innerText(), /83 registros/);
  await page.click('#next');
  assert.match(await page.locator('#page-label').innerText(), /Página 2/);
  await page.selectOption('#dataset', 'fx');
  await page.fill('#search', 'PC-0926-0162');
  assert.equal(await page.locator('#evidence-table tbody tr').count(), 2);
  const downloadPromise = page.waitForEvent('download');
  await page.click('#download');
  const download = await downloadPromise;
  await download.saveAs('analysis/download-verification.csv');
  assert.match(require('node:fs').readFileSync('analysis/download-verification.csv','utf8'),/reprocessada/);
  await page.fill('#search', 'nonexistent-record');
  assert.equal(await page.locator('#evidence-table tbody tr').count(), 0);
  await page.selectOption('#dataset', 'banks');
  assert.match(await page.locator('#result-count').innerText(), /184 registros/);
  const anchors = await page.evaluate(() => [...document.querySelectorAll('a[href^="#"]')].filter(a=>!document.getElementById(a.getAttribute('href').slice(1))).map(a=>a.href));
  assert.deepEqual(anchors, []);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  assert.equal(overflow, false);
  await page.emulateMedia({ media: 'print' });
  await page.pdf({ path: 'analysis/report-print-preview.pdf', format: 'A4', printBackground: true });
  await page.emulateMedia({ media: 'screen' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'analysis/report-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  console.log(JSON.stringify({ browser: 'Microsoft Edge', errors, externalRequests: requests.length, checks: 'counts, filtering, pagination, download, empty state, anchors, desktop/mobile overflow, print render passed' }));
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
